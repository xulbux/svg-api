/** Build and memoize the `slug -> ThemeColorName` map from `STACK_BRAND_COLORS_BY_THEME`. */
function getBrandColorBySlugMap(): Map<string, ThemeColorName> {
  if (brandColorBySlugCache === undefined) {
    const map = new Map<string, ThemeColorName>();
    for (const colorKey of Object.keys(STACK_BRAND_COLORS_BY_THEME) as ThemeColorName[]) {
      const slugs = getOwnValue(STACK_BRAND_COLORS_BY_THEME, colorKey);
      if (slugs) {
        for (const slug of slugs) {
          map.set(slug, colorKey);
        }
      }
    }
    brandColorBySlugCache = map;
  }
  return brandColorBySlugCache;
}

// -------------------------------------- PUBLIC API -------------------------------------

/**
 * Look up the official brand theme color for a canonical brand icon slug.
 * @param canonicalSlug   Canonical brand slug (lowercase, `[-_.]` stripped).
 * @returns The mapped `ThemeColorName`, or `undefined` when the slug uses the default `'indigo'` palette or is unknown.
 */
export function resolveStackBrandColor(canonicalSlug: string): ThemeColorName | undefined {
  return getBrandColorBySlugMap().get(canonicalSlug);
}
